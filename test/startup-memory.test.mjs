import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import * as THREE from 'three';
import { ATLAS_SIZE, buildAtlasTexture } from '../src/vegetation/atlas.js';
import { surfaceMap, viewSurface } from '../src/flora/surface.js';

test('foliage atlas reuses image pixels, releases its canvas, and preserves every authored mip byte', () => {
  const size = ATLAS_SIZE, padding = 12;
  const storage = new ArrayBuffer(size * size * 4 + padding * 2);
  const pixels = new Uint8ClampedArray(storage, padding, size * size * 4);
  const alpha = [0, 64, 127, 128, 129, 200, 249, 250, 255];
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const i = (y * size + x) * 4;
    pixels[i] = (x * 17 + y * 3) % 256;
    pixels[i + 1] = (x * 7 + y * 13) % 256;
    pixels[i + 2] = (x * 11 + y * 19) % 256;
    pixels[i + 3] = alpha[(x + 3 * y) % alpha.length];
  }
  let reads = 0;
  const canvas = {
    width: size, height: size,
    getContext: () => ({ getImageData: () => { reads++; return { data: pixels }; } }),
  };
  const texture = buildAtlasTexture(canvas, 0.5, [7, 11, 14, 15]);
  assert.equal(reads, 1);
  assert.equal(canvas.width, 0); assert.equal(canvas.height, 0);
  assert.equal(texture.image.data.buffer, storage, 'No second 16 MiB pixel allocation');
  assert.equal(texture.image.data.byteOffset, padding);
  assert.equal(texture.image.data.constructor, Uint8Array, 'Keep original truncation instead of clamped-array rounding');
  assert.equal(texture.image.width, size); assert.equal(texture.image.height, size);
  assert.equal(texture.mipmaps.length, 12);
  assert.equal(texture.mipmaps.reduce((sum, mip) => sum + mip.data.byteLength, 0), 22369620);
  const hash = createHash('sha256');
  for (const mip of texture.mipmaps) hash.update(mip.data);
  // Golden generated by the unmodified c0e52ba atlas builder with the same input.
  assert.equal(hash.digest('hex'), 'bdd52b1b95fe5813ab3c74726a90d2a43642ad790eedb8df06765919adf28902');
  assert.equal(texture.colorSpace, THREE.SRGBColorSpace);
  assert.equal(texture.minFilter, THREE.LinearMipmapLinearFilter);
  assert.equal(texture.anisotropy, 8);
});

function surfaceFixture(kind, fail = null) {
  const scene = new THREE.Scene();
  const mesh = new THREE.Mesh(new THREE.BoxGeometry(), new THREE.MeshStandardMaterial());
  mesh.layers.enable(29); // a pre-existing layer must not be lost on cleanup
  let previousCalls = 0;
  mesh.onBeforeRender = () => { previousCalls++; };
  scene.add(mesh);
  scene.overrideMaterial = new THREE.MeshBasicMaterial(); scene.background = new THREE.Color(0.2, 0.3, 0.4);
  const initialTarget = new THREE.WebGLRenderTarget(40, 30);
  const state = {
    target: initialTarget, face: 2, mip: 3,
    viewport: new THREE.Vector4(2, 3, 40, 30), scissor: new THREE.Vector4(4, 5, 20, 10), scissorTest: true,
    color: new THREE.Color(0.1, 0.2, 0.3), alpha: 0.6,
  };
  let targetDisposals = 0, materialDisposals = 0;
  const renderer = {
    autoClear: true, xr: { enabled: true }, shadowMap: { enabled: true, autoUpdate: true, needsUpdate: true },
    getRenderTarget: () => state.target, getActiveCubeFace: () => state.face, getActiveMipmapLevel: () => state.mip,
    setRenderTarget: (target, face = 0, mip = 0) => {
      state.target = target; state.face = face; state.mip = mip;
      if (target !== initialTarget) target.addEventListener('dispose', () => targetDisposals++);
    },
    getViewport: (v) => v.copy(state.viewport), setViewport: (v) => state.viewport.copy(v),
    getScissor: (v) => v.copy(state.scissor), setScissor: (v) => state.scissor.copy(v),
    getScissorTest: () => state.scissorTest, setScissorTest: (v) => { state.scissorTest = v; },
    getClearColor: (v) => v.copy(state.color), getClearAlpha: () => state.alpha,
    setClearColor: (v, alpha) => { state.color.set(v); state.alpha = alpha; },
    clear: () => {},
    render: (world, camera) => {
      assert.equal(world, scene);
      assert.equal(renderer.shadowMap.enabled, false, 'Construction probes must not allocate/render CSM maps');
      assert.equal(renderer.shadowMap.autoUpdate, false); assert.equal(renderer.shadowMap.needsUpdate, false);
      assert.equal(renderer.xr.enabled, false); assert.equal(state.scissorTest, false);
      assert.equal(state.target.texture.type, THREE.FloatType, 'Preserve surface placement precision');
      const material = scene.overrideMaterial;
      material.addEventListener('dispose', () => materialDisposals++);
      mesh.onBeforeRender(renderer, world, camera, mesh.geometry, material);
      assert.equal(material.uniforms.uId.value, 1);
      if (fail === 'render') throw new Error('injected render failure');
    },
    readRenderTargetPixels: (target, x, y, width, height, buffer) => {
      if (fail === 'read') throw new Error('injected read failure');
      for (let i = 0; i < buffer.length; i += 4) {
        if (kind === 'top') { buffer[i] = 12.5; buffer[i + 1] = 1; buffer[i + 2] = 1; buffer[i + 3] = 1; }
        else { buffer[i] = 3; buffer[i + 1] = 12.5; buffer[i + 2] = -7; buffer[i + 3] = 1; }
      }
    },
  };
  const snapshot = () => ({
    ...state, viewport: state.viewport.toArray(), scissor: state.scissor.toArray(), color: state.color.toArray(),
    override: scene.overrideMaterial, background: scene.background, before: mesh.onBeforeRender, layers: mesh.layers.mask,
    autoClear: renderer.autoClear, xr: renderer.xr.enabled, shadow: { ...renderer.shadowMap },
  });
  const run = () => kind === 'top'
    ? surfaceMap({ scene, renderer }, 0, 0, 16, 8)
    : viewSurface({ scene, renderer }, { pos: [0, 4, 10], target: [0, 0, 0], fov: 45 }, 8, 4);
  return { snapshot, run, mesh, counts: () => ({ targetDisposals, materialDisposals, previousCalls }) };
}

test('flora position probes preserve placement and restore renderer/scene state without drawing shadows', () => {
  for (const kind of ['top', 'view']) {
    const f = surfaceFixture(kind), before = f.snapshot();
    const result = f.run();
    assert.deepEqual(f.snapshot(), before);
    assert.equal(result.obj(0, 0), f.mesh);
    if (kind === 'top') { assert.equal(result.h(0, 0), 12.5); assert.equal(result.has(0, 0), true); }
    else assert.deepEqual(result.at(0, 0).toArray(), [3, 12.5, -7]);
    assert.deepEqual(f.counts(), { targetDisposals: 1, materialDisposals: 1, previousCalls: 1 });
  }
});

test('failed flora rendering/readback frees targets and preserves the pending first-frame shadow refresh', () => {
  for (const kind of ['top', 'view']) for (const fail of ['render', 'read']) {
    const f = surfaceFixture(kind, fail), before = f.snapshot();
    assert.throws(f.run, new RegExp(`injected ${fail} failure`));
    assert.deepEqual(f.snapshot(), before);
    assert.deepEqual(f.counts(), { targetDisposals: 1, materialDisposals: 1, previousCalls: 1 });
  }
});
